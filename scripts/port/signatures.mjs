// Generates src/engine/scmCommandSignatures.ts from the Sanny Builder library (scripts/port/.cache/sa.json, which the
// census downloads): for each command, whether it is a condition and what its output parameters are. The runtime
// uses it to skip a command it cannot run yet (see ScmThread's skip path) without leaving its outputs unwritten.
//
//   node scripts/port/signatures.mjs
import {readFileSync,writeFileSync,existsSync} from 'node:fs';
const path='scripts/port/.cache/sa.json';
if(!existsSync(path)){console.error(`${path} is missing: run \`npm run port -- census\` once to download the library.`);process.exit(1);}
const library=JSON.parse(readFileSync(path,'utf8'));
const commands=library.extensions.filter(e=>e.name==='default').flatMap(e=>e.commands);
// Outputs that name something the game made: an unanswered one is "no such thing" (-1), which the script's own
// existence tests then answer for. Numbers and enums read 0; text outputs are left alone.
const HANDLES=new Set(['Attractor','Blip','Car','CarGenerator','Char','Checkpoint','DecisionMakerChar','DecisionMakerGroup','Group','Menu','Object','Particle','Pickup','ScriptFire','Searchlight','Sequence','Sphere','Train','User3DMarker']);
const kind=type=>HANDLES.has(type)?'h':type==='float'?'f':type==='string'||type==='gxt_key'?'s':'i';
const outputs=[],conditions=[];
for(const c of commands){
 const op=parseInt(c.id,16);if(!Number.isInteger(op))continue;
 if(c.output?.length)outputs.push([op,c.output.map(o=>kind(o.type)).join('')]);
 if(c.attrs?.is_condition)conditions.push(op);
}
outputs.sort((a,b)=>a[0]-b[0]);conditions.sort((a,b)=>a-b);
const out=`// Generated by scripts/port/signatures.mjs from the Sanny Builder library (sannybuilder/library, sa/sa.json).
// Do not edit by hand.
/** Each command's output parameters, the trailing ones, by opcode: h a handle (-1 when unanswered), i an int, f a
 * float, s text (left alone). */
export const SCM_COMMAND_OUTPUTS:ReadonlyMap<number,string>=new Map(${JSON.stringify(outputs)});
/** The commands that answer a condition. */
export const SCM_CONDITION_COMMANDS:ReadonlySet<number>=new Set(${JSON.stringify(conditions)});
`;
writeFileSync('src/engine/scmCommandSignatures.ts',out);
console.log(`signatures: ${outputs.length} commands with outputs, ${conditions.length} conditions`);
