/** Generates src/audio/native/scannerTables.ts: the police scanner's tables, read out of the iOS port's executable.
 *
 * gta-reversed leaves CAEPoliceScannerAudioEntity::AddAudioEvent (0x4E71E0) unreversed, and with it the tables that
 * turn a crime into the scanner's report. The iOS port's executable (the gta3sa.app bundle,
 * github.com/Google61/gta3sa.app, decrypted, cryptid 0) has the same function in its arm64 slice at 0x100150064,
 * stripped of its name but known by what it does: it answers only AE_CRIME_COMMITTED (164) for crime types 2 to 22,
 * fills two lists of five {bank, sound} slots from the scanner banks 147 to 152 and hands them to
 * PlayPoliceScannerDialogue (0x1001503fc, which matches gta-reversed's reversal). Its tables, in __TEXT,__const:
 *  - 0x10058fde0: the three openings it picks one of (CAEAudioUtility::GetRandomNumberInRange(0, 2)), bank 150;
 *  - 0x10058fde6: each crime type's ten-code, bank 151;
 *  - 0x10058fe14 / 0x100590424 / 0x1005905a8: 194 navigation zone text keys, each one's area name in bank 147 (-1:
 *    none) and whether a direction within the zone is said before it;
 *  - 0x10059066a: each VehicleAudioTypeForName's vehicle, bank 152;
 *  - 0x1005906c6: each car colour's colour, bank 148.
 *
 * Usage: node scripts/content/scanner-tables.mjs [path to the iOS executable, gta3sa]
 * Without a path it is downloaded from the bundle's pinned revision. Either way it is checked against its hash. */
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const REVISION='67f70cb72eb207aeca650ea9e8c10b0e7dda166a';
const SOURCE={url:`https://raw.githubusercontent.com/Google61/gta3sa.app/${REVISION}/gta3sa`,bytes:14226544,
 sha256:'9bc5884cc0f671ad426b2d8143ec3db3a88c78ab756685ed4352af7a08471e78'};
const OUTPUT='src/audio/native/scannerTables.ts';
const file=process.argv[2]?await readFile(process.argv[2]):Buffer.from(await (await fetch(SOURCE.url,{signal:AbortSignal.timeout(300000)})).arrayBuffer());
if(file.length!==SOURCE.bytes||createHash('sha256').update(file).digest('hex')!==SOURCE.sha256)throw new Error('The iOS executable is not the pinned one.');
// The universal binary's arm64 slice (CPU_TYPE_ARM64), and its segments' VM addresses against file offsets.
if(file.readUInt32BE(0)!==0xcafebabe)throw new Error('Not a universal Mach-O.');
let slice=-1;
for(let i=0;i<file.readUInt32BE(4);i++)if(file.readUInt32BE(8+i*20)===0x0100000c)slice=file.readUInt32BE(8+i*20+8);
if(slice<0||file.readUInt32LE(slice)!==0xfeedfacf)throw new Error('No arm64 slice.');
const segments=[];
for(let i=0,at=slice+32;i<file.readUInt32LE(slice+16);i++){
 const cmd=file.readUInt32LE(at),size=file.readUInt32LE(at+4);
 if(cmd===0x19)segments.push({vm:Number(file.readBigUInt64LE(at+24)),fileoff:Number(file.readBigUInt64LE(at+40)),filesize:Number(file.readBigUInt64LE(at+48))});
 at+=size;
}
const offset=address=>{
 const s=segments.find(s=>address>=s.vm&&address<s.vm+s.filesize);
 if(!s)throw new Error(`Address ${address.toString(16)} is not in the file.`);
 return slice+s.fileoff+address-s.vm;
};
const int16s=(address,count)=>Array.from({length:count},(_,i)=>file.readInt16LE(offset(address)+i*2));
// The code that reads the tables, as a check that they are where it reads them: AddAudioEvent's first slot's bank (mov
// w8, #0x96) and the area loop's bound (cmp x9, #0xc2).
for(const [address,word] of [[0x1001500c8,0x528012c8],[0x100150144,0xf103093f]])if(file.readUInt32LE(offset(address))!==word)throw new Error(`Unexpected code at ${address.toString(16)}.`);
const openings=int16s(0x10058fde0,3),crimes=int16s(0x10058fde6,23),vehicles=int16s(0x10059066a,46),colours=int16s(0x1005906c6,128);
const areas=Array.from({length:194},(_,i)=>{
 const at=offset(0x10058fe14+i*8),key=file.toString('latin1',at,at+8).replace(/\0.*$/s,'');
 return [key,file.readInt16LE(offset(0x100590424)+i*2),file[offset(0x1005905a8)+i]!==0];
});
if(areas.some(([key])=>!/^[A-Z0-9_?]{1,8}$/.test(key)))throw new Error('Unexpected zone key.');
const list=values=>`[${values.join(',')}]`;
await writeFile(OUTPUT,`// Generated by scripts/content/scanner-tables.mjs from the iOS port's executable (gta3sa.app ${REVISION.slice(0,10)}, arm64).
// Do not edit by hand.
/** CAEPoliceScannerAudioEntity::AddAudioEvent's openings, of which it says one: sounds of SND_BANK_SCRIPT_SCANNER_INSTRUCTIONS. */
export const SCANNER_OPENINGS:readonly number[]=${list(openings)};
/** Each eCrimeType's ten-code, a sound of SND_BANK_SCRIPT_SCANNER_NUMBERS (-1: none; only types 2 to 22 are reported). */
export const SCANNER_CRIMES:readonly number[]=${list(crimes)};
/** Navigation zone text keys, each one's area name (a sound of SND_BANK_SCRIPT_SCANNER_AREAS, -1: none) and whether the
 * zone's direction is said before it. AddAudioEvent takes the first entry whose key is the zone's and whose sound is
 * not -1. */
export const SCANNER_AREAS:readonly (readonly [key:string,sound:number,direction:boolean])[]=[
${areas.map(([key,sound,direction])=>` [${JSON.stringify(key)},${sound},${direction}]`).join(',\n')}];
/** Each eAEVehicleAudioTypeForName's vehicle, a sound of SND_BANK_SCRIPT_SCANNER_VEHICLES. */
export const SCANNER_VEHICLES:readonly number[]=${list(vehicles)};
/** Each car colour's colour (carcols.dat's index), a sound of SND_BANK_SCRIPT_SCANNER_COLOURS. */
export const SCANNER_COLOURS:readonly number[]=${list(colours)};
`);
console.log(`${OUTPUT}: ${areas.length} areas, ${crimes.filter(c=>c>=0).length} crimes, ${vehicles.length} vehicles, ${colours.length} colours.`);
