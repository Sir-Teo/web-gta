/** Generate the two native font metric tables from the locked original-PC depot's fonts.dat.
 * Usage: node scripts/content/font-tables.mjs [path to fonts.dat]; defaults to the published local file. */
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const lock=JSON.parse(await readFile('scripts/content/world-sources.json','utf8')),source=lock.resources.find(r=>r.path==='data/fonts.dat');
if(!source)throw Error('PC fonts.dat is not locked');const SHA=source.sha256;
const bytes=await readFile(process.argv[2]??'public/play/world/files/data/fonts.dat');
if(bytes.length!==source.bytes||createHash('sha256').update(bytes).digest('hex')!==SHA)throw Error('Not the locked PC fonts.dat');
const lines=bytes.toString('latin1').split(/\r?\n/).map(s=>s.split('#')[0].trim()).filter(Boolean),fonts=[];let current;
for(let i=0;i<lines.length;i++){
 const tag=lines[i];
 if(tag==='[TOTAL_FONTS]'){if(Number(lines[++i])!==2)throw Error('Unexpected font count');}
 else if(tag==='[FONT_ID]'){const id=Number(lines[++i]);current=fonts[id]={widths:[],space:0,unproportional:0};}
 else if(tag==='[PROP]')for(let row=0;row<26;row++){const values=lines[++i].split(/\s+/).map(Number);if(values.length!==8||values.some(v=>!Number.isInteger(v)||v<0||v>255))throw Error('Invalid widths');current.widths.push(...values);}
 else if(tag==='[UNPROP]')current.unproportional=Number(lines[++i]);
 else if(tag==='[REPLACEMENT_SPACE_CHAR]')current.space=Number(lines[++i]);
}
if(fonts.length!==2||fonts.some(f=>f.widths.length!==208))throw Error('Incomplete font metrics');
const output=`// Generated by scripts/content/font-tables.mjs from the locked PC data/fonts.dat (world-sources.json).
// SHA-256 ${SHA}. Do not edit by hand.
/** gFontData: 208 proportional widths, the replacement-space character width, and fixed-width advance. */
export const NATIVE_FONT_METRICS:readonly {widths:readonly number[];space:number;unproportional:number}[]=[
${fonts.map(f=>` {widths:[\n${Array.from({length:26},(_,i)=>'  '+f.widths.slice(i*8,i*8+8).join(',')).join(',\n')}\n ],space:${f.space},unproportional:${f.unproportional}}`).join(',\n')}
];
`;
await writeFile('src/ui/nativeFontMetrics.ts',output);console.log('src/ui/nativeFontMetrics.ts: two fonts, 416 proportional widths');
