/** Generates src/audio/native/radioTables.ts: CAERadioTrackManager's track tables, read out of the iOS port's
 * executable.
 *
 * gta-reversed leaves QueueUpTracksForStation, TrackRadioStation and the Choose* functions as calls into the retail
 * executable, and with them the tables of which stream track is which. The iOS port's executable (arm64 slice; see
 * lib/ios-executable.mjs) has them in __DATA, read by its CAERadioTrackManager (the functions are named in
 * src/audio/native/NativeRadioTrackManager.ts), one row per eRadioID from 0, the emergency channel, to 11:
 *  - 0x1006450e8: each station's number of music tracks (ChooseMusicTrackIndex, 0x100155010);
 *  - 0x100645118: its music tracks, 31 a row (QueueUpTracksForStation, 0x100152768);
 *  - 0x1006456e8 / 0x100646288: each music track's intros and outros, the first and last track of a run that one is
 *    picked from (GetRandomNumberInRange);
 *  - 0x100645088: the station's idents, a run (ChooseIdentIndex, 0x1001551e8; track 1922, one past the last, is none);
 *  - 0x100644d80: the adverts every station shares, a run, and 0x100646ea4 the 23 each station never plays
 *    (ChooseAdvertIndex, 0x1001553e8; one more row there, user tracks', is all 0);
 *  - 0x100644e48 / 0x100644f68: the emergency channel's dispatcher lines, a run, and the run it plays while
 *    CGameLogic::LaRiotsActiveHere (ChooseDJBanterIndex, 0x100155834, station 0);
 *  - the tracks the iOS port removed, which its IsTrackBanned (0x100150e40) tests as runs, read out of the code.
 *
 * Usage: node scripts/content/radio-tables.mjs [path to the iOS executable, gta3sa]
 * Without a path it is downloaded from the bundle's pinned revision. Either way it is checked against its hash. */
import {writeFile} from 'node:fs/promises';
import {REVISION,readExecutable} from './lib/ios-executable.mjs';
const OUTPUT='src/audio/native/radioTables.ts';
const {int32s,word,expectCode}=await readExecutable(process.argv[2]);
// The code that reads each table (an add of its page offset), as a check that it is where it reads it.
expectCode([
 [0x100155040,0x9103a294],// ChooseMusicTrackIndex: add x20, x20, #0xe8 (the counts)
 [0x10015289c,0x9104616b],// QueueUpTracksForStation: add x11, x11, #0x118 (the music tracks)
 [0x100152950,0x911ba129],// add x9, x9, #0x6e8 (the intros)
 [0x1001528e4,0x910a22d6],// add x22, x22, #0x288 (the outros)
 [0x100155204,0x91022129],// ChooseIdentIndex: add x9, x9, #0x88
 [0x1001554c8,0x9136039c],// ChooseAdvertIndex: add x28, x28, #0xd80 (the shared run)
 [0x100155414,0x913a9108],// add x8, x8, #0xea4 (each station's restricted adverts)
 [0x100155acc,0x91392042],// ChooseDJBanterIndex, station 0: add x2, x2, #0xe48
 [0x100155ac0,0x913da042],// and add x2, x2, #0xf68 in the riots
 [0x1001558e4,0x711e091f],// cmp w8, #0x782: track 1922 stands for none
]);
const STATIONS=12,ROW=31,NO_TRACK=1922;
const counts=int32s(0x1006450e8,STATIONS);
if(counts.some(n=>n<1||n>ROW))throw new Error('Unexpected music track count.');
const runs=(address,count)=>{const v=int32s(address,count*2);return Array.from({length:count},(_,i)=>[v[i*2],v[i*2+1]]);};
const music=counts.map((n,s)=>int32s(0x100645118+s*ROW*4,n));
const intros=counts.map((n,s)=>runs(0x1006456e8+s*ROW*8,n)),outros=counts.map((n,s)=>runs(0x100646288+s*ROW*8,n));
const idents=runs(0x100645088,STATIONS),adverts=int32s(0x100644d80,2);
const restricted=Array.from({length:STATIONS+1},(_,s)=>int32s(0x100646ea4+s*0x5c,23));
const [general]=runs(0x100644e48,1),[riots]=runs(0x100644f68,1);
// IsTrackBanned: a sub of each run's first track from w0 (sub w8/w9, w0, #imm) and a compare with its length (cmp
// w8/w9, #imm, then cset lo), from its first instruction to its ret.
const banned=[];
for(let at=0x100150e40,pending;;at+=4){
 const w=word(at);
 if(w===0xd65f03c0)break;
 if((w&0xffc00000)===0x51000000&&((w>>5)&31)===0){pending=(w>>10)&0xfff;continue;}
 if((w&0xffc0001f)===0x7100001f&&pending!==undefined){banned.push([pending,(w>>10)&0xfff]);pending=undefined;}
 if(at>0x100150f40)throw new Error('IsTrackBanned has no end.');
}
if(banned.length!==15)throw new Error(`IsTrackBanned has ${banned.length} runs.`);
const all=[...music.flat(),...intros.flat(2),...outros.flat(2),...idents.flat(),...adverts,general,riots].flat();
if(all.some(t=>t<0||t>NO_TRACK))throw new Error('A track outside TrakLkup.dat.');
const json=value=>JSON.stringify(value);
await writeFile(OUTPUT,`// Generated by scripts/content/radio-tables.mjs from the iOS port's executable (gta3sa.app ${REVISION.slice(0,10)}, arm64).
// Do not edit by hand.
/** Track 1922, one past the last of TrakLkup.dat's: none. */
export const NO_TRACK=${NO_TRACK};
/** Each station's music tracks (eRadioID 0 the emergency channel, 1 to 11 the stations), which ChooseMusicTrackIndex
 * picks an index into. */
export const RADIO_MUSIC_TRACKS:readonly (readonly number[])[]=${json(music)};
/** Each music track's intros and outros: the first and last track of the run one is picked from. */
export const RADIO_INTROS:readonly (readonly (readonly [number,number])[])[]=${json(intros)};
export const RADIO_OUTROS:readonly (readonly (readonly [number,number])[])[]=${json(outros)};
/** Each station's idents, a run (NO_TRACK: none). */
export const RADIO_IDENTS:readonly (readonly [number,number])[]=${json(idents)};
/** The adverts every station shares, a run, and the ones each station (and user tracks, 12) never plays. */
export const RADIO_ADVERTS:readonly [number,number]=${json(adverts)};
export const RADIO_RESTRICTED_ADVERTS:readonly (readonly number[])[]=${json(restricted)};
/** The emergency channel's dispatcher lines, and the ones it says while the riots are on where the player is. */
export const EMERGENCY_DJ_BANTER:{readonly general:readonly [number,number];readonly riots:readonly [number,number]}={general:${json(general)},riots:${json(riots)}};
/** The tracks the iOS port removed (IsTrackBanned's runs: first track, count): never chosen, never played. */
export const BANNED_TRACKS:readonly (readonly [first:number,count:number])[]=${json(banned)};
`);
console.log(`${OUTPUT}: ${music.flat().length} music tracks over ${STATIONS} stations, ${banned.length} banned runs.`);
