/** Packages the iOS port's touch widget art into public/play/touch/widgets.png and src/input/touchWidgetArt.ts.
 *
 * The port draws each widget with a texture of its `mobile` texture database (texdb/mobile/mobile.pvr.*, read by
 * scripts/content/mobileTextureDatabase.mjs): CTouchInterface::CreateAll (arm64 0x1002a6280) makes each widget with a
 * name from the table its config load fills (0x100806e28, 128 bytes an entry), and the enter widget picks the
 * vehicle's own (0x1004afd8c). The art the touch buttons here draw is packed into one atlas of 256-pixel cells, the
 * first level of each texture, so a phone fetches one image for every button.
 *
 * Usage: node scripts/content/touch-widgets.mjs [directory holding mobile.pvr.toc, mobile.pvr.dat and mobile.txt]
 * Without a directory the files are downloaded from the bundle's pinned revision. Either way they are checked against
 * their hashes. */
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {join} from 'node:path';
import {encodePng,readTextureDatabase} from './mobileTextureDatabase.mjs';
const REVISION='67f70cb72eb207aeca650ea9e8c10b0e7dda166a',BASE=`https://raw.githubusercontent.com/Google61/gta3sa.app/${REVISION}/`;
const SOURCES={
 toc:{name:'mobile.pvr.toc',bytes:792,sha256:'8bbf2aa2ea703c3c286076805c36d4e8397a074be65b1a16a3928026651f4403'},
 dat:{name:'mobile.pvr.dat',bytes:8712314,sha256:'e9e54b41d5e161c14939ed05fed28ea037a54ebe1a2df83b136bc632c408b793'},
 txt:{name:'mobile.txt',bytes:14502,sha256:'b749f29e3c8a3b2e6d386d13b1657f082133563c0b5a87067171568b3713f4fa'},
};
/** The widgets' textures the touch buttons draw, by the port's own names: the pedals, handbrake, horn and steering
 * arrows, the lock-on, the enter widget's vehicles (and the jetpack it drops), sprint and swim, dive, crouch, nitro,
 * rockets, the camera, the phone, the Positive and Negative talk, the store's accept and cancel, the mission start, the
 * scope's zoom, the rhythm games' four arrows, the drive-by sides, the radio, the fist and the weapon swap, and the
 * attack widget's weapon pictures. */
const ART=['accelerate','brake','handbrake','horn','hud_left','hud_right','hud_lockon',
 'hud_car','hud_bike','hud_bicycle','hud_boat','hud_chopper','hud_plane','hud_monstertruck','hud_train','hud_trailer','hydraulicCar','hud_drop_jetpack',
 'sprint','hud_swim','hud_dive','hud_crouch','hud_nitro','hud_rockets','cam-toggle','hud_Cellphone','Yes','No','hud_check','hud_x','mission_start',
 'hud_plus','hud_minus','YellowArrow','BlueArrow','RedArrow','GreenArrow','leftshoot','shoot','radiostation','punch','hud_swapgun',
 // The attack widget's picture for the weapon in hand (its update, arm64 0x1004b0e68, and table 0x1005c2f00).
 'brassknuckle','hud_golfclub','hud_nightstick','hud_knife','hud_bat','shovel','hud_poolcue','hud_katana','hud_chainsaw','hud_dildo1',
 'hud_dildo2','hud_flowers','hud_cane','hud_throw','hud_teargas','flamethrower','hud_detonator','hud_spraycan','hud_extinguisher','goggles'];
const COLUMNS=8,CELL=256,OUTPUT='public/play/touch/widgets.png',MODULE='src/input/touchWidgetArt.ts';
const hash=bytes=>createHash('sha256').update(bytes).digest('hex');
async function source({name,bytes,sha256}){
 const data=process.argv[2]?await readFile(join(process.argv[2],name)):Buffer.from(await (await fetch(BASE+name,{signal:AbortSignal.timeout(300000)})).arrayBuffer());
 if(data.length!==bytes||hash(data)!==sha256)throw new Error(`${name} is not the pinned one (${data.length} bytes, ${hash(data)}).`);
 return data;
}
const [toc,dat,txt]=[await source(SOURCES.toc),await source(SOURCES.dat),await source(SOURCES.txt)];
const textures=readTextureDatabase(new Uint8Array(toc),new Uint8Array(dat),txt.toString('latin1'));
const rows=Math.ceil(ART.length/COLUMNS),atlas=new Uint8Array(COLUMNS*CELL*rows*CELL*4);
for(const [i,name] of ART.entries()){
 const texture=textures.find(t=>t.name===name);
 if(!texture)throw new Error(`The mobile database has no ${name}.`);
 if(texture.width!==CELL||texture.height!==CELL)throw new Error(`${name} is ${texture.width}x${texture.height}.`);
 const x0=i%COLUMNS*CELL,y0=Math.floor(i/COLUMNS)*CELL;
 for(let y=0;y<CELL;y++)atlas.set(texture.rgba.subarray(y*CELL*4,(y+1)*CELL*4),((y0+y)*COLUMNS*CELL+x0)*4);
}
const png=encodePng(COLUMNS*CELL,rows*CELL,atlas);
await mkdir('public/play/touch',{recursive:true});await writeFile(OUTPUT,png);
await writeFile(MODULE,`// Generated by scripts/content/touch-widgets.mjs from the iOS port's mobile texture database (gta3sa.app ${REVISION.slice(0,10)}).
// Do not edit by hand.
/** The atlas of the iOS port's touch widget art: each texture's first level in a ${CELL}-pixel cell, ${COLUMNS} to a row. */
export const TOUCH_WIDGET_ATLAS={path:'play/touch/widgets.png',columns:${COLUMNS},rows:${rows},cell:${CELL},bytes:${png.length},sha256:'${hash(png)}'} as const;
/** Each widget texture's cell, by the port's name for it. */
export const TOUCH_WIDGET_CELLS={${ART.map((name,i)=>`${JSON.stringify(name)}:${i}`).join(',')}} as const;
export type TouchWidgetArt=keyof typeof TOUCH_WIDGET_CELLS;
`);
console.log(`${OUTPUT}: ${ART.length} widgets, ${COLUMNS*CELL}x${rows*CELL}, ${(png.length/1024).toFixed(0)} KB.`);
