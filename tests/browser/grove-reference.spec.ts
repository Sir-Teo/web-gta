import {test,expect} from '@playwright/test';
import {readdirSync,writeFileSync} from 'node:fs';
test('native Grove reference lighting and grounded walking',async({page})=>{
 test.setTimeout(90000);
 const directory=process.env.GTA_REFERENCE_DIR;test.skip(!directory,'Set GTA_REFERENCE_DIR to the locally prepared native world reference.');
 const root=directory!.replace(/\/$/,'')+'/';
 await page.goto('/models.html');
 await page.getByLabel('Or open a .img archive').setInputFiles(root+'gta3.img');
 await expect(page.getByRole('status')).toContainText('directory loaded');
 await page.getByLabel('Optional .ide model definitions').setInputFiles(readdirSync(root+'definitions').filter(n=>/^(generic_|LA_|leveldes_|interior_propext|txd\.)/.test(n)).map(n=>root+'definitions/'+n));
 await expect(page.locator('#ide-status')).toContainText('model associations loaded');
 await page.getByLabel('Static .ipl for streamed LODs').setInputFiles(root+'LAe2.ipl');
 await page.getByRole('button',{name:'Select district streams',exact:true}).click();
 await expect(page.getByRole('status')).toContainText('7 archived streams selected');
 await page.getByLabel('Include all archived COL collections').check();
 await page.getByLabel('Limit scene area',{exact:true}).check();
 await page.getByRole('button',{name:'Assemble archive scene'}).click();
 await expect(page.getByRole('status')).toHaveText('Archive scene assembled locally.',{timeout:45000});
 writeFileSync('/tmp/web-gta-grove-browser-summary.txt',await page.locator('#summary').innerText()+'\n'+await page.locator('#warnings').innerText());
 await expect(page.locator('#summary')).toHaveText('171 model types · 469 placements · 0 omitted placements');
 await expect(page.getByRole('button',{name:'Walk scene',exact:true})).toBeEnabled();
 await page.getByLabel('Show collision overlay').uncheck();
 const canvas=page.getByLabel('Model preview');await canvas.hover();await page.mouse.wheel(0,-350);await page.waitForTimeout(150);
 await page.getByLabel('Model preview').screenshot({path:'artifacts/native-grove-preview.png'});
 const popup=page.waitForEvent('popup');await page.getByRole('button',{name:'Walk scene',exact:true}).click();const game=await popup;
 await expect(game.getByRole('button',{name:'Walk imported scene'})).toBeVisible();
 await game.locator('#lighting-file').setInputFiles(root+'timecycp.dat');
 await expect(game.locator('#lighting-status')).toContainText('timecycp.dat: sky, fog and building lighting loaded');
 await game.getByRole('button',{name:'Walk imported scene'}).click();
 await expect.poll(()=>game.evaluate(()=>(window as any).__game.state().imported)).toBe(true);
 await expect.poll(()=>game.evaluate(()=>(window as any).__game.state().player.grounded)).toBe(true);
 const before=await game.evaluate(()=>(window as any).__game.state());
 expect(before.player.position.x).toBeCloseTo(2495,1);expect(before.player.position.z).toBeCloseTo(1687,1);
 await game.keyboard.down('KeyW');await game.waitForTimeout(1200);await game.keyboard.up('KeyW');
 const after=await game.evaluate(()=>(window as any).__game.state());
 writeFileSync('/tmp/web-gta-grove-game-state.json',JSON.stringify({before,after}));
 expect(Math.hypot(after.player.position.x-before.player.position.x,after.player.position.z-before.player.position.z)).toBeGreaterThan(0.5);
 await game.screenshot({path:'artifacts/native-grove-timecycle.png'});
});
