import { test, expect } from '@playwright/test';
test('a local rig and locomotion clip drive the playable character and freeze with pause', async ({page}) => {
  await page.goto('/models.html');
  await page.getByLabel('Open a .dff model').setInputFiles('tests/fixtures/dragonff-skin.dff');
  await expect(page.getByRole('status')).toHaveText('dragonff-skin.dff loaded locally.');
  await page.getByLabel('Optional .ifp animations').setInputFiles('tests/fixtures/animation-rig.ifp');
  await expect(page.locator('#animation-status')).toContainText('2 tracks bound');
  await expect(page.getByRole('button',{name:'Test character in game'})).toBeDisabled();
  await page.getByLabel('Animation movement').selectOption('0');
  const popupPromise=page.waitForEvent('popup'); await page.getByRole('button',{name:'Test character in game'}).click(); const game=await popupPromise;
  const errors:string[]=[];game.on('pageerror',e=>errors.push(e.message));
  await expect(game.locator('.menu-message')).toContainText('Local locomotion clip ready');
  await game.getByRole('button',{name:'Explore Verdant Meadows',exact:true}).click();
  const state=()=>game.evaluate(()=>(window as any).__game.state());
  await expect.poll(async()=>(await state()).nativeCharacter?.visible).toBe(true);
  const start=(await state()).player.position;
  await game.keyboard.down('KeyW');
  await expect.poll(async()=>(await state()).nativeCharacter.seconds).toBeGreaterThan(.4);
  await game.keyboard.press('Escape');await game.keyboard.up('KeyW');
  const paused=await state();expect(paused.paused).toBe(true);expect(Math.hypot(paused.player.position.x-start.x,paused.player.position.z-start.z)).toBeGreaterThan(.4);
  await game.waitForTimeout(150); expect((await state()).nativeCharacter).toEqual(paused.nativeCharacter);
  await game.getByRole('button',{name:'Resume game',exact:true}).click();
  await expect.poll(async()=>(await state()).nativeCharacter.seconds).toBe(0);
  await game.keyboard.press('KeyC');
  await expect.poll(async()=>{const s=await state();return {visible:s.nativeCharacter.visible,grounded:s.player.grounded,crouched:s.player.crouched};}).toEqual({visible:false,grounded:true,crouched:true});
  await game.keyboard.press('KeyC'); await expect.poll(async()=>(await state()).nativeCharacter.visible).toBe(true);
  await game.keyboard.down('Numpad1'); await expect.poll(async()=>(await state()).camera.glance).toBe('behind');
  await game.locator('canvas.world').screenshot({path:'artifacts/native-character-game.png'});
  expect(errors).toEqual([]); await game.close();
  await page.getByRole('button',{name:'Restore bind pose'}).click();await expect(page.getByRole('button',{name:'Test character in game'})).toBeDisabled();
});

test('explicit idle walk and run assignments select native actions and clear with the model', async ({page}) => {
  await page.goto('/models.html');
  await page.getByLabel('Open a .dff model').setInputFiles('tests/fixtures/dragonff-skin.dff');
  await expect(page.getByRole('status')).toHaveText('dragonff-skin.dff loaded locally.');
  await page.getByLabel('Optional .ifp animations').setInputFiles('tests/fixtures/animation-roles.ifp');
  await expect(page.locator('#animation-status')).toContainText('Idle: 2 tracks bound');
  for(const [index,role] of [['0','idle'],['1','walk'],['2','run']]) {
    await page.getByLabel('Animation clip',{exact:true}).selectOption(index);
    await page.getByLabel('Animation movement').selectOption('0');
    await page.getByRole('button',{name:`Assign ${role}`,exact:true}).click();
  }
  await expect(page.locator('#character-assignments')).toHaveText('Idle: Idle · Walk: Walk · Run: Run · Sprint: run fallback');
  await page.getByLabel('Optional .ifp animations').setInputFiles('tests/fixtures/animation-crouch.ifp');
  await expect(page.locator('#animation-status')).toContainText('CrouchIdle: 2 tracks bound');
  await page.getByLabel('Animation movement').selectOption('0');await page.getByRole('button',{name:'Assign crouched idle',exact:true}).click();
  await expect(page.getByRole('button',{name:'Test character in game'})).toBeDisabled();
  await page.getByLabel('Animation clip',{exact:true}).selectOption('1');await page.getByLabel('Animation movement').selectOption('0');await page.getByRole('button',{name:'Assign crouched walk',exact:true}).click();
  await expect(page.locator('#character-assignments')).toHaveText('Idle: Idle · Walk: Walk · Run: Run · Sprint: run fallback');

  await page.getByLabel('Optional .ifp animations').setInputFiles('tests/fixtures/animation-rig.ifp');
  await expect(page.locator('#animation-status')).toContainText('diagnostic_turn: 2 tracks bound');
  await page.getByLabel('Animation movement').selectOption('0');await page.getByRole('button',{name:'Assign airborne',exact:true}).click();
  await page.getByRole('button',{name:'Assign landing',exact:true}).click();
  await page.getByRole('button',{name:'Assign right-foot launch',exact:true}).click();
  await expect(page.getByRole('button',{name:'Test character in game'})).toBeDisabled();
  await page.getByRole('button',{name:'Assign launch',exact:true}).click();
  await expect(page.locator('#landing-assignment')).toContainText('diagnostic_turn');
  const popup=page.waitForEvent('popup');await page.getByRole('button',{name:'Test character in game'}).click();const game=await popup;
  const errors:string[]=[];game.on('pageerror',e=>errors.push(e.message));
  await expect(game.locator('.menu-message')).toContainText('Local locomotion clip ready');await game.getByRole('button',{name:'Explore Verdant Meadows',exact:true}).click();
  const state=()=>game.evaluate(()=>(window as any).__game.state());
  await expect.poll(async()=>(await state()).nativeCharacter.seconds).toBeGreaterThan(.1);
  expect((await state()).nativeCharacter.action).toBe('idle');
  await game.keyboard.down('KeyW');await expect.poll(async()=>(await state()).nativeCharacter.action).toBe('walk');
  await game.keyboard.down('ShiftLeft');await expect.poll(async()=>(await state()).nativeCharacter.action).toBe('run');
  await expect.poll(async()=>(await state()).player.speed).toBeGreaterThan(3.5);
  await game.keyboard.up('ShiftLeft');await expect.poll(async()=>(await state()).nativeCharacter.action).toBe('walk');
  await expect.poll(async()=>(await state()).player.speed).toBeLessThan(2.1);
  await game.keyboard.up('KeyW');await expect.poll(async()=>(await state()).nativeCharacter.action).toBe('idle');
  await game.keyboard.press('KeyC');await expect.poll(async()=>(await state()).nativeCharacter.action).toBe('crouchIdle');expect((await state()).nativeCharacter.visible).toBe(true);
  const stamina=(await state()).player.stamina;await game.keyboard.down('ShiftLeft');await game.keyboard.down('KeyW');
  await expect.poll(async()=>(await state()).nativeCharacter.action).toBe('crouchWalk');await expect.poll(async()=>(await state()).player.speed).toBeLessThan(1.1);
  expect((await state()).player.stamina).toBeGreaterThanOrEqual(stamina);await game.keyboard.up('KeyW');await game.keyboard.up('ShiftLeft');
  await game.keyboard.down('Numpad1');await expect.poll(async()=>(await state()).camera.glance).toBe('behind');await game.locator('canvas.world').screenshot({path:'artifacts/native-crouch-game.png'});await game.keyboard.up('Numpad1');
  await game.keyboard.press('KeyC');await expect.poll(async()=>(await state()).nativeCharacter.action).toBe('idle');
  await game.keyboard.press('Space');await expect.poll(async()=>(await state()).nativeCharacter.action).toBe('launch');
  expect((await state()).player.grounded).toBe(true);
  await game.keyboard.press('Escape');const launchFrozen=(await state()).nativeCharacter;await game.waitForTimeout(150);expect((await state()).nativeCharacter).toEqual(launchFrozen);
  await game.getByRole('button',{name:'Resume game',exact:true}).click();
  await expect.poll(async()=>(await state()).nativeCharacter.action, { intervals: [50] }).toBe('airborne');expect((await state()).nativeCharacter.visible).toBe(true);
  await game.keyboard.press('Escape');const frozen=(await state()).nativeCharacter;await game.waitForTimeout(120);expect((await state()).nativeCharacter).toEqual(frozen);
  const pausedPosition=(await state()).player.position;await game.waitForTimeout(100);expect((await state()).player.position).toEqual(pausedPosition);
  await game.getByRole('button',{name:'Resume game',exact:true}).click();
  await expect.poll(async()=>(await state()).nativeCharacter.action).toBe('landing');
  await game.keyboard.down('KeyW');await game.keyboard.press('Space');await game.waitForTimeout(100);
  expect((await state()).nativeCharacter.action).toBe('landing');expect((await state()).player.grounded).toBe(true);
  await game.keyboard.up('KeyW');
  await game.locator('canvas.world').screenshot({path:'artifacts/native-landing-game.png'});
  await expect.poll(async()=>(await state()).nativeCharacter.action).toBe('idle');expect((await state()).player.grounded).toBe(true);
  await game.keyboard.down('KeyW');
  await expect.poll(async()=>{const n=(await state()).nativeCharacter;return n.action==='walk' && n.seconds%2>.4 && n.seconds%2<.7;}, {intervals:[50]}).toBe(true);
  await game.keyboard.press('Space');await game.keyboard.up('KeyW');
  await expect.poll(async()=>(await state()).nativeCharacter.action,{intervals:[50]}).toBe('launchRight');
  await expect.poll(async()=>(await state()).nativeCharacter.action,{intervals:[50]}).toBe('airborne');
  await expect.poll(async()=>(await state()).nativeCharacter.action).toBe('idle');
  expect(errors).toEqual([]);await game.close();
  await page.getByRole('button',{name:'Clear / cancel',exact:true}).click();await expect(page.locator('#character-assignments')).toContainText('Run: walk fallback');
  await expect(page.getByRole('button',{name:'Test character in game'})).toBeDisabled();
});
